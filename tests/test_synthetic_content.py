"""What the synthetic fixture SAYS, asserted against the mail we wrote.

Every vendor store in the corpus proves that structures parse. None can prove
that a message says what it should, because nobody here wrote the mail.
`tests/fixtures/public/synth-basics.pst` is different: it was generated by
`scripts/make_fixture.py` from `tests/fixtures/synthetic/basics/`, seven
`.eml` files we authored with example.test addresses and invented names. The
sources are the expectation; the store is the thing under test.

Three tiers, in order of how much of the port they need:

1. **Goldens** (no pypst code): folder names and message counts from the
   oracle's `read_ipm_subtree` / `read_root_folder`, the store's display name
   and derived record key from `read_store_props`, and the admission fact
   itself — the oracle exits 0 on every example that matters.
2. **Bytes** (no pypst code): EMLtoPST writes an UNENCRYPTED store
   (`bCryptMethod` = 0, asserted first), so a PT_UNICODE value sits in the
   file as plain UTF-16LE and an attachment as its raw bytes. Searching the
   file for the authored subject is crude, but it is a real content assertion
   available today, and it pins the generator: if the tool ever encodes,
   compresses or mangles a value, this tier says so before P09 exists.
3. **The reader** (skips until P07–P09 land): the same expectations read back
   through `pypst.Store` / `Folder` / `Message` / `Attachment`, written to
   `docs/INTERFACES.md` § messaging so they go live without edits.

Plus the policy tests that keep future synthetic sources honest, and the
regeneration check that keeps the committed store honest.
"""

